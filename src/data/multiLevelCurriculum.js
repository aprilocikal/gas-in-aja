export function getCurriculumForLang(langId) {
  return (
    multiLevelCurriculum[langId] ||
    defaultUnits(langId.charAt(0).toUpperCase() + langId.slice(1), '#6366f1')
  )
}

export function computeUnitUnlockStatus(langId, earnedXP) {
  const curriculum = getCurriculumForLang(langId)
  return curriculum.units.map((unit) => ({
    ...unit,
    isUnlocked: earnedXP >= unit.requiredXP,
    isCompleted: earnedXP >= (unit.requiredXP + unit.modules.reduce((s, m) => s + m.xpReward, 0)),
  }))
}
