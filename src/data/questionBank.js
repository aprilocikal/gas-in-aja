function shuffleArray(list) {
  const arr = [...list]
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

function hashModuleSeed(str) {
  let h = 2166136261
  const s = String(str || '')
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

function rotateWithModuleSeed(list, seed) {
  if (list.length <= 1) return [...list]
  const offset = seed % list.length
  return [...list.slice(offset), ...list.slice(0, offset)]
}

function extractKeywords(moduleMeta) {
  const raw = `${moduleMeta?.moduleTitle || ''} ${moduleMeta?.moduleDesc || ''}`
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
  const stopWords = new Set(['dan', 'yang', 'atau', 'dengan', 'untuk', 'pada', 'dari', 'dalam', 'secara', 'cara', 'dasar'])
  return raw
    .split(/\s+/)
    .filter((w) => w.length >= 2 && !stopWords.has(w))
}

function scoreQuestion(q, keywords) {
  if (!keywords.length) return 0
  const haystack = [
    ...(q.tags || []),
    (q.title || '').toLowerCase(),
    (q.prompt || '').toLowerCase(),
  ].join(' ')

  let score = 0
  for (const kw of keywords) {
    if ((q.tags || []).some((t) => t.toLowerCase().includes(kw) || kw.includes(t.toLowerCase()))) {
      score += 3
    } else if (haystack.includes(kw)) {
      score += 1
    }
  }
  return score
}

function isValidQuestion(q) {
  if (!q || typeof q !== 'object' || !q.type || !q.title) return false
  if (q.type === 'word_bank') {
    return Array.isArray(q.targetSequence) && q.targetSequence.length > 0
  }
  return (
    Array.isArray(q.options) &&
    q.options.length > 0 &&
    typeof q.correctAnswer === 'number' &&
    q.correctAnswer >= 0 &&
    q.correctAnswer < q.options.length
  )
}

/**
 * Generate a randomized, topic-tailored lesson pack for a given programming language and module.
 * Prioritizes module topic keywords and varies selection per moduleId so every module feels distinct.
 */
export function generateRandomLessonPack(langId = 'python', count = 6, moduleMeta = {}) {
  const normalized = (langId || 'python').toLowerCase()
  const keywords = extractKeywords(moduleMeta)
  const seed = hashModuleSeed(`${normalized}-${moduleMeta?.moduleId || ''}-${moduleMeta?.moduleTitle || ''}`)

  const rankPool = (pool) => {
    const valid = pool.filter(isValidQuestion)
    const rotated = rotateWithModuleSeed(valid, seed)
    return rotated
      .map((q, idx) => ({
        q,
        score: scoreQuestion(q, keywords),
        jitter: Math.random() * 0.65,
        tieOrder: idx,
      }))
      .sort((a, b) => b.score + b.jitter - (a.score + a.jitter))
      .map((item) => item.q)
  }

  const langPool = rankPool(QUESTION_BANK.filter((q) => q.lang === normalized))
  const generalPool = rankPool(QUESTION_BANK.filter((q) => q.lang === 'general'))
  const fallbackPool = rankPool(
    QUESTION_BANK.filter((q) => q.lang !== normalized && q.lang !== 'general')
  )

  const targetCount = Math.max(1, count)
  const combined = [
    ...langPool.slice(0, Math.min(4, targetCount)),
    ...generalPool.slice(0, 3),
    ...langPool.slice(4),
    ...generalPool.slice(3),
    ...fallbackPool,
  ]

  const uniqueMap = new Map()
  for (const item of combined) {
    if (isValidQuestion(item) && !uniqueMap.has(item.id)) {
      uniqueMap.set(item.id, item)
    }
    if (uniqueMap.size >= targetCount) break
  }

  let selected = Array.from(uniqueMap.values()).filter(isValidQuestion)

  // Guarantee at least one interactive word_bank syntax builder question when available
  if (!selected.some((q) => q.type === 'word_bank') && selected.length > 0) {
    const wbCandidate =
      langPool.find((q) => q.type === 'word_bank') ||
      generalPool.find((q) => q.type === 'word_bank') ||
      fallbackPool.find((q) => q.type === 'word_bank')
    if (wbCandidate) {
      selected[selected.length - 1] = wbCandidate
    }
  }

  selected = shuffleArray(selected).filter(isValidQuestion)

  return selected.map((q, qIdx) => {
    if (q.type === 'word_bank') {
      const tokens = [...q.targetSequence, ...(q.distractors || [])]
      const chips = tokens.map((text, cIdx) => ({
        id: `q${qIdx}-c${cIdx}-${q.id}`,
        text,
      }))
      return {
        ...q,
        shuffledChips: shuffleArray(chips),
      }
    }

    const correctText = q.options[q.correctAnswer]
    const shuffledOptions = shuffleArray(q.options)
    const nextCorrect = shuffledOptions.indexOf(correctText)
    return {
      ...q,
      options: shuffledOptions,
      correctAnswer: nextCorrect >= 0 ? nextCorrect : 0,
    }
  })
}
